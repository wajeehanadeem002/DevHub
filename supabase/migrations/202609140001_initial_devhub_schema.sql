-- DevHub initial application schema.
-- Identity is owned by Clerk; application ownership uses auth.jwt()->>'sub'.

create table public.profiles (
  user_id text primary key default (auth.jwt() ->> 'sub'),
  username text not null unique,
  display_name text not null,
  headline text,
  bio text,
  location text,
  country_code text,
  website_url text,
  github_url text,
  linkedin_url text,
  avatar_path text,
  is_public boolean not null default true,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector generated always as (
    setweight(to_tsvector('simple', coalesce(username, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(display_name, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(headline, '')), 'B') ||
    setweight(to_tsvector('simple', coalesce(bio, '')), 'C') ||
    setweight(to_tsvector('simple', coalesce(location, '')), 'D')
  ) stored,
  constraint profiles_user_id_length check (char_length(user_id) between 1 and 255),
  constraint profiles_username_format check (
    username = lower(username)
    and username ~ '^[a-z0-9][a-z0-9_]{1,28}[a-z0-9]$'
  ),
  constraint profiles_display_name_length check (
    char_length(btrim(display_name)) between 1 and 80
  ),
  constraint profiles_headline_length check (
    headline is null or char_length(headline) between 1 and 120
  ),
  constraint profiles_bio_length check (bio is null or char_length(bio) <= 1000),
  constraint profiles_location_length check (
    location is null or char_length(location) <= 100
  ),
  constraint profiles_country_code_format check (
    country_code is null or country_code ~ '^[A-Z]{2}$'
  ),
  constraint profiles_website_url_format check (
    website_url is null or (char_length(website_url) <= 500 and website_url ~ '^https?://')
  ),
  constraint profiles_github_url_format check (
    github_url is null or (char_length(github_url) <= 500 and github_url ~ '^https?://')
  ),
  constraint profiles_linkedin_url_format check (
    linkedin_url is null or (char_length(linkedin_url) <= 500 and linkedin_url ~ '^https?://')
  ),
  constraint profiles_avatar_path_length check (
    avatar_path is null or char_length(avatar_path) between 1 and 500
  )
);

create table public.categories (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now(),
  constraint categories_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint categories_name_length check (char_length(btrim(name)) between 1 and 60),
  constraint categories_sort_order_check check (sort_order >= 0)
);

create table public.technologies (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  name text not null unique,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now(),
  constraint technologies_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint technologies_name_length check (char_length(btrim(name)) between 1 and 60),
  constraint technologies_sort_order_check check (sort_order >= 0)
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  owner_id text not null default (auth.jwt() ->> 'sub')
    references public.profiles(user_id) on delete cascade,
  category_id smallint not null references public.categories(id) on delete restrict,
  title text not null,
  summary text not null,
  description text not null,
  demo_url text,
  repository_url text,
  status text not null default 'draft',
  published_at timestamptz,
  like_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search_document tsvector generated always as (
    setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
    setweight(to_tsvector('english', coalesce(summary, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(description, '')), 'C')
  ) stored,
  constraint projects_title_length check (char_length(btrim(title)) between 1 and 120),
  constraint projects_summary_length check (char_length(btrim(summary)) between 1 and 240),
  constraint projects_description_length check (
    char_length(btrim(description)) between 1 and 10000
  ),
  constraint projects_demo_url_format check (
    demo_url is null or (char_length(demo_url) <= 500 and demo_url ~ '^https?://')
  ),
  constraint projects_repository_url_format check (
    repository_url is null or (char_length(repository_url) <= 500 and repository_url ~ '^https?://')
  ),
  constraint projects_status_check check (status in ('draft', 'published')),
  constraint projects_like_count_check check (like_count >= 0)
);

create table public.project_images (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  storage_path text not null unique,
  alt_text text not null,
  sort_order smallint not null,
  mime_type text not null,
  byte_size integer not null,
  width integer not null,
  height integer not null,
  created_at timestamptz not null default now(),
  constraint project_images_project_order_unique unique (project_id, sort_order),
  constraint project_images_storage_path_length check (
    char_length(storage_path) between 1 and 500
  ),
  constraint project_images_alt_text_length check (
    char_length(btrim(alt_text)) between 1 and 200
  ),
  constraint project_images_slot_check check (sort_order between 0 and 4),
  constraint project_images_mime_type_check check (
    mime_type in ('image/avif', 'image/jpeg', 'image/png', 'image/webp')
  ),
  constraint project_images_byte_size_check check (byte_size between 1 and 10485760),
  constraint project_images_dimensions_check check (
    width between 1 and 10000 and height between 1 and 10000
  )
);

create table public.project_technologies (
  project_id uuid not null references public.projects(id) on delete cascade,
  technology_id smallint not null references public.technologies(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (project_id, technology_id)
);

create table public.profile_technologies (
  user_id text not null default (auth.jwt() ->> 'sub')
    references public.profiles(user_id) on delete cascade,
  technology_id smallint not null references public.technologies(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (user_id, technology_id)
);

create table public.project_likes (
  project_id uuid not null references public.projects(id) on delete cascade,
  user_id text not null default (auth.jwt() ->> 'sub')
    references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (project_id, user_id)
);

create table public.project_saves (
  project_id uuid not null references public.projects(id) on delete cascade,
  user_id text not null default (auth.jwt() ->> 'sub')
    references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (project_id, user_id)
);

create table public.clerk_webhook_events (
  event_id text primary key,
  event_type text not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  processed_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clerk_webhook_events_event_id_length check (
    char_length(event_id) between 1 and 255
  ),
  constraint clerk_webhook_events_event_type_length check (
    char_length(event_type) between 1 and 120
  ),
  constraint clerk_webhook_events_status_check check (
    status in ('pending', 'processing', 'completed', 'failed')
  ),
  constraint clerk_webhook_events_attempts_check check (attempts >= 0),
  constraint clerk_webhook_events_last_error_length check (
    last_error is null or char_length(last_error) <= 4000
  )
);

