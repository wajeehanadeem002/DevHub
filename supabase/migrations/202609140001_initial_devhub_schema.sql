create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.set_project_published_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.status = 'published' then
    if tg_op = 'INSERT' or old.status <> 'published' then
      new.published_at = now();
    end if;
  else
    new.published_at = null;
  end if;

  return new;
end;
$$;

create or replace function public.sync_project_like_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    update public.projects
      set like_count = like_count + 1
      where id = new.project_id;
    return new;
  end if;

  update public.projects
    set like_count = greatest(like_count - 1, 0)
    where id = old.project_id;
  return old;
end;
$$;

revoke all on function public.sync_project_like_count() from public;
revoke all on function public.sync_project_like_count() from anon, authenticated;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create trigger projects_set_updated_at
before update on public.projects
for each row execute function public.set_updated_at();

create trigger projects_set_published_at
before insert or update of status on public.projects
for each row execute function public.set_project_published_at();

create trigger clerk_webhook_events_set_updated_at
before update on public.clerk_webhook_events
for each row execute function public.set_updated_at();

create trigger project_likes_sync_count
after insert or delete on public.project_likes
for each row execute function public.sync_project_like_count();

