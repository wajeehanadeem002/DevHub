create policy "Public profiles are readable"
on public.profiles for select to anon
using (is_public and deleted_at is null);

create policy "Authenticated users read public or own profile"
on public.profiles for select to authenticated
using (
  (is_public and deleted_at is null)
  or user_id = (select auth.jwt() ->> 'sub')
);

create policy "Users create their own profile"
on public.profiles for insert to authenticated
with check (
  user_id = (select auth.jwt() ->> 'sub')
  and deleted_at is null
);

create policy "Users update their own active profile"
on public.profiles for update to authenticated
using (
  user_id = (select auth.jwt() ->> 'sub')
  and deleted_at is null
)
with check (
  user_id = (select auth.jwt() ->> 'sub')
  and deleted_at is null
);

